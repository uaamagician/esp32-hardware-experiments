    if (!reset) begin
        cnt_tick <= 0;
        hold     <= 0;
        idx      <= 0;
        cur      <= 0;
        cnt_scan <= 0;
    end else begin
        cnt_scan <= cnt_scan + 1'b1;
        cur      <= rom[idx];
        if (cnt_tick >= TICK) begin
            cnt_tick <= 0;
            if (hold + 1'b1 >= dur) begin
                hold <= 0;
